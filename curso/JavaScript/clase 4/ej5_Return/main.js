/*------Las funciones pueden generar un valor de retorno usando la palabra return, obteniendo el valor cuando la funcion es llamada------*/

function sumar(primerNumero, segundoNumero){
    return primerNumero + segundoNumero;
}

let resultado = sumar (5, 8);
 
/*---En este ejemplo la funcion recibe dos parametros y devuelve la suma de ellos permitiendonos asignar ese nuevo valor a una variable---*/

console.log(resultado);
